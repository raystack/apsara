/**
 * Generates `icons/generated/` from `icons/icon-map.json`:
 *
 *   - one module per icon key, so a bundler removes an unused icon at a module
 *     boundary (no aggregate map anywhere in the graph),
 *   - `index.tsx`, the barrel,
 *   - `types.ts`, the `IconName` union (types only, no runtime bytes).
 *
 * The output is committed, exactly as `icons/index.tsx` is. Run
 * `pnpm build:icon-registry` after editing the map.
 */

const fs = require('fs');
const path = require('path');

const ICON_FOLDER = path.join(__dirname, '..', 'icons');
const ICON_MAP = path.join(ICON_FOLDER, 'icon-map.json');
const OUT_FOLDER = path.join(ICON_FOLDER, 'generated');

const HEADER = `// This file is automatically generated by "pnpm build:icon-registry"
// Do not edit this file manually
`;

/** `CircleXIcon` -> `circle-x-icon`, `AArrowDownIcon` -> `a-arrow-down-icon`. */
const toKebabCase = name =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();

/** `co-pilot.svg` -> `CoPilot`. */
const toPascalCase = filename =>
  path
    .basename(filename, '.svg')
    .replace(/(^|[-_])(.)/g, (_, __, char) => char.toUpperCase());

// biome's line width is 80, and the formatter runs over the generated files.
// Emit the wrapped call itself rather than let `pnpm lint` fail on 123 files.
const LINE_WIDTH = 80;

const declaration = (key, local) => {
  const oneLine = `export const ${key} = /*#__PURE__*/ createIcon('${key}', ${local});`;
  if (oneLine.length <= LINE_WIDTH) return oneLine;
  return `export const ${key} = /*#__PURE__*/ createIcon(
  '${key}',
  ${local}
);`;
};

const lucideModule = (key, lucideName) => `${HEADER}'use client';

import { ${lucideName} } from 'lucide-react';
import { createIcon } from '../create-icon';

${declaration(key, lucideName)}
`;

const assetModule = (key, asset) => {
  const local = toPascalCase(asset);
  return `${HEADER}'use client';

import { ReactComponent as ${local} } from '../assets/${asset}';
import { createIcon } from '../create-icon';

${declaration(key, local)}
`;
};

function main() {
  const map = JSON.parse(fs.readFileSync(ICON_MAP, 'utf8'));
  const keys = Object.keys(map);

  const files = new Map();
  const modules = [];

  for (const key of keys) {
    const value = map[key];
    const basename = toKebabCase(key);

    const collision = files.get(basename);
    if (collision) {
      throw new Error(
        `${key} and ${collision} both produce the filename ${basename}.tsx`
      );
    }
    files.set(basename, key);

    if (typeof value === 'string') {
      if (value === key) {
        throw new Error(
          `${key}: the lucide name must not equal the key, or the module ` +
            'would shadow its own export'
        );
      }
      modules.push({ key, basename, source: lucideModule(key, value) });
      continue;
    }

    if (value && typeof value === 'object' && typeof value.asset === 'string') {
      modules.push({
        key,
        basename,
        source: assetModule(key, value.asset)
      });
      continue;
    }

    throw new Error(
      `${key}: value must be a lucide export name or { "asset": "x.svg" }`
    );
  }

  // Rewrite from empty so a key removed from the map cannot leave an orphan.
  fs.rmSync(OUT_FOLDER, { recursive: true, force: true });
  fs.mkdirSync(OUT_FOLDER, { recursive: true });

  for (const { basename, source } of modules) {
    fs.writeFileSync(path.join(OUT_FOLDER, `${basename}.tsx`), source);
  }

  // biome's `organizeImports` assist sorts re-exports by module specifier, so
  // emit that order. The `IconName` union below stays in map order — biome does
  // not sort the members of a union type.
  const sorted = [...modules].sort((a, b) =>
    a.basename < b.basename ? -1 : a.basename > b.basename ? 1 : 0
  );

  const barrel =
    HEADER +
    '\n' +
    sorted
      .map(({ key, basename }) => `export { ${key} } from './${basename}';`)
      .join('\n') +
    '\n';
  fs.writeFileSync(path.join(OUT_FOLDER, 'index.tsx'), barrel);

  const union = `${HEADER}
/** Every icon name that Apsara ships. A consumer overrides an icon by name. */
export type IconName =
${keys.map(key => `  | '${key}'`).join('\n')};
`;
  fs.writeFileSync(path.join(OUT_FOLDER, 'types.ts'), union);

  console.log(
    `icons/generated: ${modules.length} modules, the barrel, and the IconName union`
  );
}

main();
